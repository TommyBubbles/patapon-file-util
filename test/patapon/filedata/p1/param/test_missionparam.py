    def test_from_bytes(self,
            mission_param_header: SystemDataMissionParamHeader,
            mission_param_last_element: MissionParam,
            mission_param_extra_param_last_element: SystemDataMissionParamExtraParamElement
            ):
        file_name = "D:\\Patapon\\Patapon Stuff\\Patapon 1 US\\@DATA_CMN\\loadinggroup\\@systemdata\\@default\\@loadinggroupcmn\\@paramlist\\missionparam.dat"
        with open(file_name, "rb") as file:
            raw = file.read()
            actual: SystemDataMissionParam = SystemDataMissionParam.from_bytes(raw)
            assert SystemDataMissionParam.verify_filler(actual)

        assert actual.get_byte_size() == 0x13B40

        assert actual.header.get_byte_size() == 0x40
        assert actual.header == mission_param_header

        assert len(actual.mission_params.param_list) == 0x3f
        assert actual.mission_params.param_list[-1].get_byte_size() == 0x400
        assert actual.mission_params.param_list[-1] == mission_param_last_element

        assert len(actual.extra_params.param_list) == 0x3f
        assert actual.extra_params.param_list[-1].get_byte_size() == 0x100
        assert actual.extra_params.param_list[-1] == mission_param_extra_param_last_element



